-- Inventory Service - estoque e reservas.

CREATE TABLE inventory_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT                   NOT NULL,
    quantity_on_hand  INTEGER                  NOT NULL,
    quantity_reserved INTEGER                  NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    version           BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uk_inventory_items_product UNIQUE (product_id),
    CONSTRAINT ck_inventory_on_hand_non_negative CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_inventory_reserved_range CHECK (quantity_reserved >= 0 AND quantity_reserved <= quantity_on_hand)
);

CREATE TABLE reservations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference  VARCHAR(64)              NOT NULL,
    status     VARCHAR(20)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reservations_reference UNIQUE (reference),
    CONSTRAINT ck_reservations_status CHECK (status IN ('RESERVED', 'COMMITTED', 'RELEASED'))
);

CREATE TABLE reservation_lines (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT  NOT NULL,
    product_id     BIGINT  NOT NULL,
    quantity       INTEGER NOT NULL,
    CONSTRAINT fk_reservation_lines_reservation FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT ck_reservation_lines_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_reservation_lines_reservation ON reservation_lines (reservation_id);
